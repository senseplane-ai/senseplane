// Writes tests/fixtures/webhook-vectors.json with the TypeScript SDK's own
// signWebhook and verifyWebhook, so the Python SDK is tested against the same
// outcomes. Run after `pnpm --filter senseplane build`: node scripts/webhook-vectors.mjs
import { writeFileSync } from "node:fs";
import { signWebhook, verifyWebhook } from "../../typescript/dist/webhooks.js";

const secret = "whsec_test_vectors_only";
const body = JSON.stringify({ id: "evt_01JABCDEFGHJKMNPQRSTVWXYZ0", type: "sensor.threshold", source: { id: "src_1", sense: "temperature" }, summary: "Kitchen: temperature is 30 celsius, above 25." });
const unicode = JSON.stringify({ id: "evt_2", type: "watch.triggered", summary: "Someone at the café door — ünïcode ✓" });
const t = 1_760_000_000;
const good = signWebhook(body, secret, t);
const mac = good.split("v1=")[1];

const cases = [
  { name: "valid", body, header: good, now: t },
  { name: "valid within tolerance", body, header: good, now: t + 300 },
  { name: "valid with spaces", body, header: `t=${t}, v1=${mac}`, now: t },
  { name: "valid with uppercase hex", body, header: `t=${t},v1=${mac.toUpperCase()}`, now: t },
  { name: "valid with extra parts", body, header: `t=${t},v0=abc,v1=${mac}`, now: t },
  { name: "valid unicode body", body: unicode, header: signWebhook(unicode, secret, t), now: t },
  { name: "stale", body, header: good, now: t + 301 },
  { name: "from the future", body, header: good, now: t - 301 },
  { name: "tampered body", body: body + " ", header: good, now: t },
  { name: "wrong secret", body, header: signWebhook(body, "whsec_other", t), now: t },
  { name: "missing header", body, header: "", now: t },
  { name: "no v1", body, header: `t=${t}`, now: t },
  { name: "no timestamp", body, header: `v1=${mac}`, now: t },
  { name: "bad timestamp", body, header: `t=soon,v1=${mac}`, now: t },
  { name: "truncated signature", body, header: `t=${t},v1=${mac.slice(0, 32)}`, now: t },
  { name: "not hex", body, header: `t=${t},v1=${"z".repeat(64)}`, now: t },
];

const vectors = cases.map((c) => {
  let outcome = "valid";
  try {
    verifyWebhook(c.body, c.header || undefined, secret, { now: c.now });
  } catch (err) {
    outcome = err.message;
  }
  return { ...c, outcome };
});
const out = { $comment: "Copyright 2026 The Senseplane Authors. SPDX-License-Identifier: Apache-2.0. Generated by scripts/webhook-vectors.mjs from the TypeScript SDK.", secret, sign: { body, timestamp: t, header: good }, vectors };
writeFileSync(new URL("../tests/fixtures/webhook-vectors.json", import.meta.url), JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${vectors.length} vectors`);
